logger = logging.getLogger(__name__)

# Scheduler instance & execution lock
_scheduler: Optional[BackgroundScheduler] = None
_scheduler_cycle_lock = threading.Lock()


def get_config_value(db: Session, key: str, default: int) -> int:
    cfg = db.query(SystemConfig).filter(SystemConfig.key == key).first()
    if cfg and cfg.value:
        try:
            return int(cfg.value)
        except ValueError:
            pass
    return default


def generate_daily_supervisor_summary(db: Session, sim_now: datetime) -> Optional[DailySupervisorSummary]:
    """
    Standout Feature 4: Daily Supervisor Summary generated by scheduled job.
    """
    today_str = sim_now.strftime("%Y-%m-%d")
    existing = db.query(DailySupervisorSummary).filter(DailySupervisorSummary.date == today_str).first()
    if existing:
        return existing

    total_cases = db.query(Complaint).count()
    pending_cases = db.query(Complaint).filter(Complaint.status.notin_(["Resolved", "Closed"])).count()
    overdue_cases = db.query(Complaint).filter(Complaint.is_overdue == True, Complaint.status.notin_(["Resolved", "Closed"])).count()
    escalated_cases = db.query(Complaint).filter(Complaint.is_escalated == True, Complaint.status.notin_(["Resolved", "Closed"])).count()
    
    # Resolved today
    resolved_today = db.query(Complaint).filter(
        Complaint.status.in_(["Resolved", "Closed"]),
        func.date(Complaint.updated_at) == today_str
    ).count()

    summary_text = (
        f"DAILY EXECUTIVE COMMAND SUMMARY — {today_str}\n"
        f"State Grievance Monitoring & Accountability Bureau (KSP Pilot)\n\n"
        f"• Active Workload: {pending_cases} cases currently under investigation across divisions (Total Registered: {total_cases}).\n"
        f"• Critical Escalations: {escalated_cases} cases have exceeded 3-day overdue SLA and demand supervisory intervention.\n"
        f"• Overdue Status: {overdue_cases} cases currently breach statutory follow-up deadlines.\n"
        f"• Resolution Progress: {resolved_today} grievances were successfully resolved/closed today.\n"
        f"Supervisory Action Required: Prioritize urgent reassignment for cases in Cyber Crime and Economic Offences wings exceeding 72h inactivity."
    )

    summary_entry = DailySupervisorSummary(
        date=today_str,
        total_cases=total_cases,
        pending_cases=pending_cases,
        overdue_cases=overdue_cases,
        escalated_cases=escalated_cases,
        resolved_today=resolved_today,
        summary_text=summary_text,
        created_at=sim_now
    )
    db.add(summary_entry)
    db.flush()
    return summary_entry


def run_scheduler_cycle(db: Optional[Session] = None) -> Dict[str, Any]:
    """
    Core accountability engine:
    Evaluates complaints against simulated clock (get_now()).
    Dispatches reminders, flags overdue, escalates to supervisors, red-flags 7-day delays,
    detects silent complaints, and creates cryptographic audit logs without duplicate spam.
    Thread-synchronized with _scheduler_cycle_lock to prevent concurrent execution.
    """
    with _scheduler_cycle_lock:
        return _run_scheduler_cycle_impl(db=db)


def _run_scheduler_cycle_impl(db: Optional[Session] = None) -> Dict[str, Any]:
    close_db = False
    if db is None:
        db = SessionLocal()
        close_db = True

    try:
        sim_now = get_now()
        
        # Load configurable thresholds
        remind_hours = get_config_value(db, "reminder_hours_before", 24)
        esc_days = get_config_value(db, "overdue_escalation_days", 3)
        red_days = get_config_value(db, "overdue_redflag_days", 7)
        silent_days = get_config_value(db, "silent_complaint_days", 4)

        # Find supervisory officers to notify
        supervisor = db.query(User).filter(User.role == "senior_supervisor").first()

        # Query all active non-resolved complaints
        active_complaints = db.query(Complaint).filter(
            Complaint.status.notin_(["Resolved", "Closed"])
        ).all()

        reminders_sent = 0
        overdue_flagged = 0
        escalations_triggered = 0
        red_flags_triggered = 0
        silent_flagged = 0

        for comp in active_complaints:
            officer = db.query(User).filter(User.id == comp.assigned_officer_id).first()
            if not officer:
                continue

            time_diff = (comp.due_date - sim_now).total_seconds()

            # 1. REMINDER: 24h before due date (within reminder window and not yet expired)
            if 0 < time_diff <= (remind_hours * 3600):
                # Check if reminder already logged
                event_key = f"reminder_24h_{comp.id}_{comp.due_date.strftime('%Y%m%d%H')}"
                notif = notify_reminder_24h(db, comp, officer)
                if notif:
                    reminders_sent += 1

            # 2. OVERDUE: Due date has elapsed
            if sim_now > comp.due_date:
                if not comp.is_overdue:
                    comp.is_overdue = True
                    overdue_flagged += 1
                    
                    # Log in cryptographic audit ledger
                    log_action(
                        db=db,
                        complaint_id=comp.id,
                        action="DEADLINE_VIOLATION",
                        user_id=None,
                        user_name="CIVANTA SLA Escalation Engine",
                        user_role="system",
                        old_status=comp.status,
                        new_status=comp.status,
                        description=(
                            f"Statutory follow-up deadline of {comp.due_date.strftime('%Y-%m-%d %H:%M')} expired. "
                            f"Marked as OVERDUE. Alert dispatched to Officer {officer.name} and Station In-Charge."
                        ),
                        timestamp=sim_now
                    )
                    notify_case_overdue(db, comp, officer, supervisor)

            # 3. ESCALATION: Overdue by >= 3 days
            overdue_seconds = (sim_now - comp.due_date).total_seconds()
            if overdue_seconds >= (esc_days * 86400):
                if not comp.is_escalated:
                    comp.is_escalated = True
                    comp.escalated_at = sim_now
                    comp.escalation_level = max(comp.escalation_level, 1)
                    escalations_triggered += 1

                    log_action(
                        db=db,
                        complaint_id=comp.id,
                        action="ESCALATION",
                        user_id=None,
                        user_name="CIVANTA SLA Escalation Engine",
                        user_role="system",
                        old_status=comp.status,
                        new_status=comp.status,
                        description=(
                            f"Case has remained overdue for {esc_days}+ days without resolution. "
                            f"Automatically elevated to Senior Police Supervisor ({supervisor.name if supervisor else 'Command'}) "
                            f"for accountability audit or reassignment."
                        ),
                        timestamp=sim_now
                    )
                    if supervisor:
                        notify_case_escalated_3d(db, comp, supervisor, officer)

            # 4. RED FLAG: Overdue by >= 7 days
            if overdue_seconds >= (red_days * 86400):
                if comp.escalation_level < 2:
                    comp.escalation_level = 2
                    red_flags_triggered += 1

                    log_action(
                        db=db,
                        complaint_id=comp.id,
                        action="DEADLINE_VIOLATION",
                        user_id=None,
                        user_name="CIVANTA SLA Escalation Engine",
                        user_role="system",
                        old_status=comp.status,
                        new_status=comp.status,
                        description=(
                            f"SEVERE ACCOUNTABILITY VIOLATION: Case has been overdue for {red_days}+ days. "
                            f"Flagged in RED on Supervisory Command Console."
                        ),
                        timestamp=sim_now
                    )
                    if supervisor:
                        notify_red_flag_7d(db, comp, supervisor)

            # 5. SILENT COMPLAINT DETECTOR: No officer activity for N days
            if comp.last_activity_at:
                inactivity_days = (sim_now - comp.last_activity_at).days
                if inactivity_days >= silent_days:
                    # Notify supervisor
                    if supervisor:
                        notify_silent_complaint(db, comp, supervisor, officer, inactivity_days)
                        silent_flagged += 1

        # 6. Generate Daily Summary
        generate_daily_supervisor_summary(db, sim_now)

        db.commit()

        return {
            "simulated_time": sim_now.isoformat(),
            "active_complaints_checked": len(active_complaints),
            "reminders_sent": reminders_sent,
            "overdue_flagged": overdue_flagged,
            "escalations_triggered": escalations_triggered,
            "red_flags_triggered": red_flags_triggered,
            "silent_flagged": silent_flagged
        }

    except Exception as exc:
        logger.error(f"Error in scheduler execution cycle: {exc}", exc_info=True)
        db.rollback()
        raise
    finally:
        if close_db:
            db.close()


def start_background_scheduler():
    """Starts APScheduler background job running every 60 seconds."""
    global _scheduler
    if _scheduler is not None and _scheduler.running:
        return

    _scheduler = BackgroundScheduler(daemon=True)
    _scheduler.add_job(
        func=run_scheduler_cycle,
        trigger="interval",
        seconds=60,
        id="civanta_accountability_engine",
        replace_existing=True,
        max_instances=1
    )
    _scheduler.start()
    logger.info("CIVANTA APScheduler background accountability engine started.")


def stop_background_scheduler():
    global _scheduler
    if _scheduler and _scheduler.running:
        _scheduler.shutdown(wait=False)
        logger.info("CIVANTA APScheduler background engine stopped.")
